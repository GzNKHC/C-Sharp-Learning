IF DB_ID(N'QLCuaHang') IS NULL
    CREATE DATABASE QLCuaHang;
GO
USE QLCuaHang;
GO

IF OBJECT_ID(N'CHITIET_HOADON', N'U') IS NOT NULL DROP TABLE CHITIET_HOADON;
IF OBJECT_ID(N'TONKHO', N'U') IS NOT NULL DROP TABLE TONKHO;
IF OBJECT_ID(N'HOADON', N'U') IS NOT NULL DROP TABLE HOADON;
IF OBJECT_ID(N'SANPHAM', N'U') IS NOT NULL DROP TABLE SANPHAM;
GO

CREATE TABLE SANPHAM(
    MaSP int IDENTITY(1,1) NOT NULL PRIMARY KEY,
    TenSP nvarchar(150) NOT NULL
);

CREATE TABLE HOADON(
    MaHD int IDENTITY(1,1) NOT NULL PRIMARY KEY,
    NgayTao date NOT NULL DEFAULT CAST(GETDATE() AS date),
    TinhTrangThanhToan bit NOT NULL DEFAULT 0
);

CREATE TABLE CHITIET_HOADON(
    MaHD int NOT NULL,
    MaSP int NOT NULL,
    SoLuong int NOT NULL,
    CONSTRAINT PK_CTHD PRIMARY KEY(MaHD, MaSP),
    CONSTRAINT FK_CTHD_HD FOREIGN KEY(MaHD) REFERENCES HOADON(MaHD),
    CONSTRAINT FK_CTHD_SP FOREIGN KEY(MaSP) REFERENCES SANPHAM(MaSP),
    CONSTRAINT CK_CTHD_SL CHECK(SoLuong > 0)
);

CREATE TABLE TONKHO(
    MaSP int NOT NULL,
    NgayTon date NOT NULL,
    SLDau int NOT NULL DEFAULT 0,
    SLNhap int NOT NULL DEFAULT 0,
    SLBan int NOT NULL DEFAULT 0,
    CONSTRAINT PK_TONKHO PRIMARY KEY(MaSP, NgayTon),
    CONSTRAINT FK_TONKHO_SP FOREIGN KEY(MaSP) REFERENCES SANPHAM(MaSP)
);
GO

